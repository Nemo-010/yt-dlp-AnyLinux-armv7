#!/bin/sh
# armv7-anywrap.sh - turn an existing dynamically-linked armv7 ELF into a
# self-contained bundle: its own loader and the whole DT_NEEDED closure taken
# from a sysroot. Nothing is rebuilt from source.
#
#   ./armv7-anywrap.sh -r <sysroot> [-o <outdir>] <binary> [extra files/dirs...]
#
# The sysroot is any extracted armhf/armv7h tree (a Debian .deb set, an Alpine
# apk tree, an Arch Linux ARM rootfs). Only the loader and libraries are taken
# from it.
#
# Output: <outdir>/lib  <outdir>/app  <outdir>/AppRun
#
# It prints the payload's CPU/FPU attributes and warns about what bundling
# cannot fix: an instruction set above the armv7 baseline, a payload linked
# statically against glibc, or a payload built against bionic. Those need a
# rebuild, not a wrapper.

set -eu

SYSROOT=
OUT=bundle-$(date +%s)
while [ $# -gt 0 ]; do
	case $1 in
		-r) SYSROOT=$2; shift 2 ;;
		-o) OUT=$2; shift 2 ;;
		*) break ;;
	esac
done
[ $# -ge 1 ] || { echo "usage: $0 -r <sysroot> [-o <outdir>] <binary> [extra...]" >&2; exit 2; }
[ -n "$SYSROOT" ] && [ -d "$SYSROOT" ] || { echo "error: -r <sysroot> is required and must exist" >&2; exit 2; }

BIN=$1; shift
[ -f "$BIN" ] || { echo "error: no such file: $BIN" >&2; exit 2; }

need_of() {
	readelf -d "$1" 2>/dev/null | awk '/NEEDED/ { gsub(/[][]/, "", $NF); print $NF }'
}
find_lib() {
	find "$SYSROOT" -name "$1" \( -type f -o -type l \) 2>/dev/null | head -n 1
}

# -- 0. what we were handed ------------------------------------------------
hdr=$(readelf -h "$BIN" 2>/dev/null || true)
printf '%s' "$hdr" | grep -q 'Machine:.*ARM' || { echo "error: not an ARM ELF" >&2; exit 1; }
printf '%s' "$hdr" | grep -q 'Version5 EABI' || echo "warning: not EABI5, check the ABI" >&2
printf '%s' "$hdr" | grep -q 'hard-float ABI' || echo "warning: not hard-float" >&2

attr=$(readelf -A "$BIN" 2>/dev/null || true)
cpu=$(printf '%s' "$attr" | sed -n 's/.*Tag_CPU_arch: //p' | head -n 1)
fp=$(printf '%s' "$attr" | sed -n 's/.*Tag_FP_arch: //p' | head -n 1)
simd=$(printf '%s' "$attr" | sed -n 's/.*Tag_Advanced_SIMD_arch: //p' | head -n 1)
echo "payload:  $BIN"
echo "  cpu=$cpu fp=$fp simd=${simd:-none}"
[ -n "$simd" ] && echo "  note: payload uses $simd; it will SIGILL on non-NEON ARMv7 and no"
[ -n "$simd" ] && echo "        amount of bundling changes that - only a rebuild does."
case $fp in
	VFPv4*) echo "  note: $fp needs vfma, i.e. Cortex-A7/A15 or newer" ;;
esac

# -- 1. collect the closure ------------------------------------------------
rm -rf "$OUT"
mkdir -p "$OUT/lib" "$OUT/app"

loader=
for cand in ld-linux-armhf.so.3 ld-musl-armhf.so.1 ld-linux.so.3 ld-musl-arm.so.1; do
	l=$(find_lib "$cand")
	[ -n "$l" ] && { loader=$l; break; }
done
[ -n "$loader" ] || { echo "error: no armhf loader in $SYSROOT" >&2; exit 1; }
loadername=$(basename "$loader")
cp -L "$loader" "$OUT/lib/$loadername"
chmod +x "$OUT/lib/$loadername"
echo "loader:   $loadername ($(wc -c < "$OUT/lib/$loadername" | tr -d ' ') bytes)"

queue=$(need_of "$BIN" | grep -v '^ld-' || true)
: > "$OUT/.seen"
n=0
while [ -n "$queue" ]; do
	rest=
	for lib in $queue; do
		grep -qxF "$lib" "$OUT/.seen" && continue
		echo "$lib" >> "$OUT/.seen"
		src=$(find_lib "$lib")
		if [ -z "$src" ]; then
			echo "  MISSING  $lib (not in sysroot)" >&2
			continue
		fi
		cp -L "$src" "$OUT/lib/$lib"
		n=$((n + 1))
		more=$(need_of "$src" | grep -v '^ld-' || true)
		for m in $more; do
			grep -qxF "$m" "$OUT/.seen" || rest="$rest $m"
		done
	done
	queue=$rest
done
echo "libs:     $n copied ($(du -sk "$OUT/lib" | awk '{print $1}') KiB)"
rm -f "$OUT/.seen"

# -- 2. the payload --------------------------------------------------------
name=$(basename "$BIN")
cp "$BIN" "$OUT/app/$name"
chmod +x "$OUT/app/$name"
for extra in "$@"; do
	[ -e "$extra" ] || { echo "warning: skipping missing $extra" >&2; continue; }
	cp -a "$extra" "$OUT/app/"
done

# -- 3. the launcher ------------------------------------------------------
cat > "$OUT/AppRun" <<EOF
#!/bin/sh
# generated by armv7-anywrap.sh - runs the payload through its own loader
dir=\$(CDPATH= cd -- "\$(dirname -- "\$0")" && pwd)
exec "\$dir/lib/$loadername" --library-path "\$dir/lib" "\$dir/app/$name" "\$@"
EOF
chmod +x "$OUT/AppRun"

echo "bundle:   $OUT ($(du -sk "$OUT" | awk '{print $1}') KiB)"
echo "run:      \$ $OUT/AppRun --help"
echo "          or, with no sh on the host:"
echo "          \$ <arm-emulator> $OUT/lib/$loadername --library-path $OUT/lib $OUT/app/$name --help"
